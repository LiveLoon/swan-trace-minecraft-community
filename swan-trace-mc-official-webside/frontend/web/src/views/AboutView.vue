<script setup lang="ts">
import AvatarC from '@/components/AvatarC.vue'
import FooterC from '@/components/FooterC.vue'
import { onMounted, onUnmounted, ref } from 'vue'

/**
 * 页面主体
 */
const aboutSection = ref<HTMLElement | null>(null)

/**
 * 页面整体 Observer
 */
let sectionObserver: IntersectionObserver | null = null

/**
 * 页面模块 Observer
 */
let blockObserver: IntersectionObserver | null = null

onMounted(() => {
  /**
   * 页面整体淡入
   */
  if (aboutSection.value) {
    sectionObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) {
            return
          }

          entry.target.classList.add('is-visible')

          sectionObserver?.unobserve(entry.target)
        })
      },
      {
        threshold: 0.05,
        rootMargin: '0px 0px -40px 0px'
      }
    )

    sectionObserver.observe(aboutSection.value)
  }

  /**
   * 各个内容模块依次出现
   */
  const blocks =
    document.querySelectorAll<HTMLElement>('.about-block')

  blockObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return
        }

        entry.target.classList.add('block-visible')

        blockObserver?.unobserve(entry.target)
      })
    },
    {
      threshold: 0.08,
      rootMargin: '0px 0px -40px 0px'
    }
  )

  blocks.forEach((block) => {
    blockObserver?.observe(block)
  })
})

/**
 * 页面销毁时释放 Observer
 */
onUnmounted(() => {
  sectionObserver?.disconnect()
  blockObserver?.disconnect()

  sectionObserver = null
  blockObserver = null
})
</script>

